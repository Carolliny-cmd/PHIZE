/// Devolve a parte registrável de [dominioNormalizado] (saída de
/// `normalizarDominio`), ou `null` quando o próprio endereço é uma
/// categoria do Registro.br, como "gov.br": não há nome registrado para
/// consultar.
String? registravelDe(String dominioNormalizado) {
  final rotulos = dominioNormalizado.split('.');
  final ehBr = rotulos.last == 'br';
  final penultimo = rotulos[rotulos.length - 2];

  if (ehBr && categoriasDominioBr.contains(penultimo)) {
    if (rotulos.length == 2) return null;
    return rotulos.sublist(rotulos.length - 3).join('.');
  }
  return rotulos.sublist(rotulos.length - 2).join('.');
}
